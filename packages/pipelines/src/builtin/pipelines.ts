import type { Pipeline, Stage } from "../schema.ts";

const gates: Stage = {
  id: "gates",
  role: "gatekeeper",
  goal: "Run the project's checks: format, lint, type check, unit tests, a secret scan, and a dependency audit where the project has them. Set exact commands in .pipelines/pipelines/<name>.yaml.",
  produces: ["gates.json"],
  onFail: "build",
};

/** The security sub-pipeline. `backTo` is the stage a confirmed critical or high finding returns to. */
const securityStages = (backTo: string | undefined): ReadonlyArray<Stage> => [
  {
    id: "security-scope",
    role: "security-scout",
    goal: "Pick the security reviewers this diff needs.",
    reads: ["threat-model.md"],
    produces: ["security-scope.json"],
  },
  {
    id: "security-review",
    role: "security-reviewer",
    goal: "One worker per reviewer named in security-scope.json, in parallel, each hunting one vulnerability class.",
    reads: ["security-scope.json", "threat-model.md"],
    produces: ["findings.json"],
    parallel: 4,
  },
  {
    id: "security-validate",
    role: "security-validator",
    goal: "Re-prove or reject every finding. Confirmed critical or high findings fail the stage; needs_human findings become a question for the user.",
    reads: ["findings.json"],
    produces: ["validated.json"],
    differentProviderFrom: "security-review",
    skipWhen: "findings.json is empty",
    ...(backTo === undefined ? {} : { onFail: backTo }),
  },
];

